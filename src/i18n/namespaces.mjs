// Message namespaces: one JSON file per namespace in messages/<locale>/.
// labels.json and errors.json are not namespaces: they are looked up by their English
// text (which can contain dots) through src/i18n/dictionaries.ts.
// After adding one here, run `node src/i18n/namespaces.mjs` to regenerate messages.ts.
export const NAMESPACES = [
  "common",
  "nav",
  "auth",
  "ui",
  "becomeOrganizer",
  "events",
  "checkout",
  "orders",
  "support",
  "organizer",
  "wizard",
  "ticketTypes",
  "paidActivation",
  "staff",
  "eventActions",
  "analytics",
  "campaigns",
  "supportInbox",
  "admin",
];
export const LOCALES = ["kk", "ru", "en"];

import { writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    "../..",
  );
  const lines = [
    "// Generated by src/i18n/namespaces.mjs. Do not edit by hand.",
    "",
  ];
  for (const l of LOCALES)
    for (const ns of NAMESPACES) {
      const file = path.join(root, "messages", l, `${ns}.json`);
      if (!existsSync(file)) writeFileSync(file, "{}\n");
      lines.push(`import ${l}_${ns} from "../../messages/${l}/${ns}.json";`);
    }
  lines.push("", "export const MESSAGES = {");
  for (const l of LOCALES)
    lines.push(
      `  ${l}: { ${NAMESPACES.map((ns) => `${ns}: ${l}_${ns}`).join(", ")} },`,
    );
  lines.push("} as const;", "");
  writeFileSync(path.join(root, "src/i18n/messages.ts"), lines.join("\n"));
  console.log("wrote src/i18n/messages.ts");
}
